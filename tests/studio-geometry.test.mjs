import assert from 'node:assert/strict';
import {createProject,addFurniture} from '../site/src/studio-model.js';
import {calculateRooms,materialTakeoff,furnitureDiagnostics,suggestLayout,pointInPolygon} from '../site/src/studio-geometry.js';
const project=createProject();
const rooms=calculateRooms(project.walls);
assert.equal(rooms.length,2,'Full-length partition should divide the building');
assert.ok(Math.abs(rooms.reduce((s,r)=>s+r.area,0)-68)<.01);
assert.ok(rooms.every(r=>r.area>20));
assert.ok(rooms.every(r=>pointInPolygon(r.centroid,r.polygon)));
const qty=materialTakeoff(project);
assert.equal(qty.totalFloorAreaM2,68);
assert.ok(qty.openingAreaM2>2);
assert.ok(qty.netWallAreaM2<qty.grossWallAreaM2);
const copies=suggestLayout({...project,furniture:[]},['sofa','bed']);
assert.ok(copies.length>=1,'Smart room layout must propose usable furniture');
assert.equal(furnitureDiagnostics({...project,furniture:copies}).length,0);
const bad=createProject(),f=addFurniture(bad,'sofa');f.x=5.9;
assert.ok(furnitureDiagnostics(bad).some(e=>e.type==='boundary'));
const overlap=createProject();const a=addFurniture(overlap,'sofa'),b=addFurniture(overlap,'bed');
a.x=2;a.z=0;b.x=2;b.z=0;
assert.ok(furnitureDiagnostics(overlap).some(e=>e.type==='overlap'));
assert.deepEqual(calculateRooms([{a:[0,0],b:[3,0]},{a:[3,0],b:[3,4]}]),[]);
console.log('Studio geometry tests passed: rooms, net wall surfaces, safe layout and collision');
