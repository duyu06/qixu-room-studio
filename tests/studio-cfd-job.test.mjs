import assert from 'node:assert/strict';
import {createProject} from '../site/src/studio-model.js';
import {buildCfdJob} from '../site/src/studio-cfd-job.js';
const doc=createProject();
const input=buildCfdJob(doc,{pressurePa:12,maxCellSize:.4});
assert.equal(input.schema,'qixu-cfd-job');
assert.equal(input.units,'m');assert.equal(input.axis,'Y-up');
assert.equal(input.physics.inletPressurePa,12);
assert.equal(input.walls.length,doc.walls.length);
assert.equal(input.openings.length,doc.openings.length);
assert.equal(input.status,'input-only');
assert.throws(()=>buildCfdJob(doc,{pressurePa:NaN}),/压差/);
assert.throws(()=>buildCfdJob(doc,{maxCellSize:0}),/网格/);
assert.throws(()=>buildCfdJob(doc,{openings:{[doc.openings[0].id]:0}}),/进风口/);
doc.furniture.push({id:'f1',type:'table',x:0,z:0,width:1.2,depth:.6,height:.8,rotation:Math.PI/2});
const withFurniture=buildCfdJob(doc);
assert.deepEqual(withFurniture.furniture[0].center,[0,.4,0]);
assert.equal(withFurniture.furniture[0].rotationY,-Math.PI/2);
console.log('CFD job input validation passed');
