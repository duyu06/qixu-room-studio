import assert from 'node:assert/strict';
import {createProject,validateProject} from '../site/src/studio-model.js';
import {wallJunctions} from '../site/src/studio-wall-junctions.js';
import {moveWallJoint,translateWallWithJoints} from '../site/src/studio-wall-joints.js';
const d=createProject();
const w=d.walls[0];
w.layer='decor';w.faceAColor='#abcdef';w.faceBColor='#123456';w.locked=true;
w.faceAPattern='plaster';w.faceBPattern='wallpaper';w.faceARepeat=4;w.faceBRepeat=8;
assert.equal(validateProject(d),null);
w.faceAPattern='invalid';assert.match(validateProject(d),/纹理类型/);
w.faceAPattern='plaster';w.faceBRepeat=13;assert.match(validateProject(d),/重复次数/);
w.faceBRepeat=8;
assert.equal(validateProject(d),null);
w.faceAColor='red';assert.match(validateProject(d),/墙面颜色/);
w.faceAColor='#abcdef';w.layer='wrong';assert.match(validateProject(d),/墙体图层/);
w.layer='IFC_WALL';assert.equal(validateProject(d),null);
w.layer='decor';w.locked='yes';assert.match(validateProject(d),/锁定/);
const joint={thickness:.14,wallHeight:2.8,walls:[{id:'a',a:[0,0],b:[2,0]},{id:'b',a:[2,0],b:[2,2]},{id:'c',a:[2,1],b:[4,1]}]};
const corners=wallJunctions(joint);
assert.ok(corners.some(p=>p.x===2&&p.z===0&&p.count===2));
assert.ok(corners.some(p=>p.x===2&&p.z===1&&p.count===2));
joint.walls[1].locked=true;
assert.throws(()=>moveWallJoint(joint,'a','b',[3,0]),/锁定/);
assert.deepEqual(joint.walls[0].b,[2,0]);
assert.throws(()=>translateWallWithJoints(joint,'a',1,0),/锁定/);
console.log('Wall layers faces L/T junction and locks verified');
