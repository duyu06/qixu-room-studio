import assert from 'node:assert/strict';
import {sunCalcToScene} from '../site/src/solar-model.js';
import {makeCfdInput} from '../site/src/cfd-export.js';
const near=(x,y)=>assert.ok(Math.abs(x-y)<1e-8, x+' != '+y);
const east=sunCalcToScene({altitude:Math.PI/6,azimuth:-Math.PI/2});
near(east.altitudeDeg,30);near(east.bearingDeg,90);near(east.direction.x,Math.cos(Math.PI/6));
near(sunCalcToScene({altitude:.2,azimuth:0}).bearingDeg,180);
near(sunCalcToScene({altitude:.2,azimuth:Math.PI/2}).bearingDeg,270);
near(sunCalcToScene({altitude:.2,azimuth:-Math.PI/2},90).direction.z,-Math.cos(.2));
const plan={w:8,d:6,crop:{left:0,right:800,top:0,bottom:600},walls:[[0,0,800,0]],furniture:[]};
const c=makeCfdInput(plan,{door:{x:3,z:0},window:{x:-3,z:0}});
near(c.geometry.walls[0].a[0],-4);assert.equal(c.status,'UNVALIDATED_GEOMETRY_ONLY');
assert.throws(()=>makeCfdInput(plan,{door:{x:0,z:0},window:{x:0,z:0}}));
console.log('Sun angle conversion and CFD export tests passed');
