import assert from 'node:assert/strict';
import {createProject,addFurniture} from '../site/src/studio-model.js';
import {studioToRenderPayload,renderWallPieces} from '../site/src/studio-render-bridge.js';
const studio=createProject();studio.title='试运行';addFurniture(studio,'sofa');
const item=studioToRenderPayload(studio);
assert.equal(item.plan.w,12);assert.equal(item.plan.d,9);
assert.equal(item.plan.walls.length,5);assert.equal(item.source,'qixu-studio');
assert.equal(item.plan.furniture.length,1);
assert.equal(item.image,null);
const full=renderWallPieces(studio,'high');
const low=renderWallPieces(studio,'low');
assert.ok(full.length>studio.walls.length,'Openings should cause split wall pieces');
assert.ok(low.every(piece=>piece.y+piece.height/2<=1.2+.0001));
assert.ok(full.some(piece=>piece.y+piece.height/2>2.5));
const center=studio.walls[4];
const vertical=full.filter(p=>p.wallId===center.id);
const door=studio.openings.find(o=>o.wallId===center.id);
const len=Math.hypot(center.b[0]-center.a[0],center.b[1]-center.a[1]);
const mid=[center.a[0]+(center.b[0]-center.a[0])*door.t,center.a[1]+(center.b[1]-center.a[1])*door.t];
assert.ok(!vertical.some(p=>p.y<p.height/2+.05&&Math.hypot(p.x-mid[0],p.z-mid[1])<door.width/2-.02));
console.log('Studio render payload, real door void, clipped walls and preview geometry passed');
